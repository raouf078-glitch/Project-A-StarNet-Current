// عدد نقاط البيع داخل منطقة
export function countRegionPoints(region) {
  return region.sections.reduce((sum, s) => sum + s.points.length, 0)
}

// إجمالي نقاط البيع في كل المناطق
export function totalPoints() {
  return POS_REGIONS.reduce((sum, r) => sum + countRegionPoints(r), 0)
}
